export function getPlatformById(id: CommunityPlatformId): CommunityPlatform | undefined {
  return COMMUNITY_PLATFORMS.find((p) => p.id === id);
}

export function defaultCtaLabel(category: CommunityCategory): string {
  switch (category) {
    case 'community':
      return 'Join Community →';
    case 'channel':
      return 'Follow Channel →';
    case 'newsletter':
      return 'Subscribe →';
    case 'social':
      return 'Follow →';
    case 'resource':
      return 'View →';
  }
}
