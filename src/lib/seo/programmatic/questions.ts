/**
 * Filters questions eligible for FAQ schema (`tip` or `keywords` present)
 * and formats them as { question, answer } pairs for `faqPageJsonLd()`.
 *
 * Accepts any question array so it works across all three registry types.
 *
 * @param questions  Flat question array from any *QuestionsFlat helper.
 * @param maxItems   Cap at this many FAQ pairs (default 10 — Google recommends ≤10).
 */
export function buildFaqPairs(
  questions: readonly SeoQuestion[],
  maxItems = 10,
): Array<{ question: string; answer: string }> {
  return questions
    .filter((q) => q.tip !== undefined || (q.keywords && q.keywords.length > 0))
    .slice(0, maxItems)
    .map((q) => ({
      question: q.question,
      // Prefer tip as the human-readable answer; fall back to keywords joined.
      answer: q.tip ?? (q.keywords ? `Key concepts: ${q.keywords.join(', ')}.` : ''),
    }))
}

